-- ============================================================================
-- PROJETO: SISTEMA DE TREINOS E METAS (TRE_)
-- SCRIPT DDL: DEFINIÇÃO DE ESTRUTURA DE DADOS
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. DROP DE TABELAS (Ordem correta: filhas antes das mães)
-- ----------------------------------------------------------------------------
DROP TABLE TRE_RECORD;
DROP TABLE TRE_SERIE;
DROP TABLE TRE_ITEM_TREINO;
DROP TABLE TRE_TREINO;
DROP TABLE TRE_META;
DROP TABLE TRE_EXERCICIO;
DROP TABLE TRE_GRUPOMUSCULAR;
DROP TABLE TRE_USUARIO;


-- ============================================================================
-- 2. CRIAÇÃO DAS TABELAS
-- ============================================================================

-- ----------------------------------------------------------------------------
-- TABELA: TRE_USUARIO
-- Armazena os usuários/alunos do sistema.
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_USUARIO (
    ID_USUARIO        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COD_USUARIO       VARCHAR2(50) NOT NULL,
    NOME              VARCHAR2(150) NOT NULL,
    EMAIL             VARCHAR2(150) NOT NULL,
    SENHA             VARCHAR2(255) NOT NULL,
    DATA_CADASTRO     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_TRE_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_TRE_USUARIO_COD UNIQUE (COD_USUARIO),
    CONSTRAINT UK_TRE_USUARIO_EMAIL UNIQUE (EMAIL)
);


-- ----------------------------------------------------------------------------
-- TABELA: TRE_GRUPOMUSCULAR
-- Categorias musculares (ex: Peitoral, Costas, Pernas).
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_GRUPOMUSCULAR (
    ID_GRP_MUSCULAR   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    COD_GRP_MUSCULAR  VARCHAR2(50) NOT NULL,
    NOME              VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_TRE_GRUPOMUSCULAR PRIMARY KEY (ID_GRP_MUSCULAR),
    CONSTRAINT UK_TRE_GRP_COD UNIQUE (COD_GRP_MUSCULAR)
);


-- ----------------------------------------------------------------------------
-- TABELA: TRE_EXERCICIO
-- Exercícios cadastrados. Se ID_USUARIO for NULO, é exercício padrão global.
-- Se ID_USUARIO estiver preenchido, é um exercício customizado criado por ele.
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_EXERCICIO (
    ID_EXERCICIO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO        NUMBER,
    ID_GRP_MUSCULAR   NUMBER NOT NULL,
    COD_EXERCICIO     VARCHAR2(50) NOT NULL,
    NOME              VARCHAR2(100) NOT NULL,
    DESCRICAO         VARCHAR2(1000),

    CONSTRAINT PK_TRE_EXERCICIO PRIMARY KEY (ID_EXERCICIO),
    CONSTRAINT UK_TRE_EXC_COD UNIQUE (COD_EXERCICIO),
    CONSTRAINT FK_EXC_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TRE_USUARIO(ID_USUARIO),
    CONSTRAINT FK_EXC_GRUPO FOREIGN KEY (ID_GRP_MUSCULAR) REFERENCES TRE_GRUPOMUSCULAR(ID_GRP_MUSCULAR)
);


-- ----------------------------------------------------------------------------
-- TABELA: TRE_META
-- Metas de progressão de carga estabelecidas por usuário e exercício.
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_META (
    ID_META           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO        NUMBER NOT NULL,
    ID_EXERCICIO      NUMBER NOT NULL,
    COD_META          VARCHAR2(50) NOT NULL,
    CARGA_ALVO        NUMBER(6,2) NOT NULL,
    DATA_CRIACAO      DATE NOT NULL,
    DATA_ALVO         DATE NOT NULL,
    DATA_CONCLUSAO    DATE,
    STATUS            VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_TRE_META PRIMARY KEY (ID_META),
    CONSTRAINT UK_TRE_META_COD UNIQUE (COD_META),
    CONSTRAINT FK_META_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TRE_USUARIO(ID_USUARIO),
    CONSTRAINT FK_META_EXC FOREIGN KEY (ID_EXERCICIO) REFERENCES TRE_EXERCICIO(ID_EXERCICIO),
    CONSTRAINT CK_META_STATUS CHECK (STATUS IN ('ATIVA', 'CONCLUIDA', 'CANCELADA'))
);


-- ----------------------------------------------------------------------------
-- TABELA: TRE_RECORD
-- Histórico de recordes batidos pelos usuários ao longo do tempo.
-- Cada linha representa um marco de carga atingido em determinada data.
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_RECORD (
    ID_RECORD         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO        NUMBER NOT NULL,
    ID_EXERCICIO      NUMBER NOT NULL,
    COD_RECORD        VARCHAR2(50) NOT NULL,
    CARGA_RECORD      NUMBER(6,2) NOT NULL,
    DATA_RECORD       DATE NOT NULL,

    CONSTRAINT PK_TRE_RECORD PRIMARY KEY (ID_RECORD),
    CONSTRAINT UK_TRE_RECORD_COD UNIQUE (COD_RECORD),
    CONSTRAINT FK_RECORD_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TRE_USUARIO(ID_USUARIO),
    CONSTRAINT FK_RECORD_EXERCICIO FOREIGN KEY (ID_EXERCICIO) REFERENCES TRE_EXERCICIO(ID_EXERCICIO)
);


-- ----------------------------------------------------------------------------
-- TABELA: TRE_TREINO
-- Sessão de treino executada por um usuário em determinada data.
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_TREINO (
    ID_TREINO         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO        NUMBER NOT NULL,
    COD_TREINO        VARCHAR2(50) NOT NULL,
    DATA_TREINO       DATE NOT NULL,
    DURACAO_MINUTO    NUMBER,
    OBSERVACOES       VARCHAR2(1000),

    CONSTRAINT PK_TRE_TREINO PRIMARY KEY (ID_TREINO),
    CONSTRAINT UK_TRE_TREINO_COD UNIQUE (COD_TREINO),
    CONSTRAINT FK_TRN_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TRE_USUARIO(ID_USUARIO)
);


-- ----------------------------------------------------------------------------
-- TABELA: TRE_ITEM_TREINO
-- Exercícios executados dentro de uma sessão de treino.
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_ITEM_TREINO (
    ID_ITEM_TREINO    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_TREINO         NUMBER NOT NULL,
    ID_EXERCICIO      NUMBER NOT NULL,
    ORDEM             NUMBER NOT NULL,

    CONSTRAINT PK_TRE_ITEM_TREINO PRIMARY KEY (ID_ITEM_TREINO),
    CONSTRAINT FK_ITEM_TREINO FOREIGN KEY (ID_TREINO) REFERENCES TRE_TREINO(ID_TREINO),
    CONSTRAINT FK_ITEM_EXC FOREIGN KEY (ID_EXERCICIO) REFERENCES TRE_EXERCICIO(ID_EXERCICIO)
);


-- ----------------------------------------------------------------------------
-- TABELA: TRE_SERIE
-- Detalhes das séries realizadas para cada exercício no treino.
-- ----------------------------------------------------------------------------
CREATE TABLE TRE_SERIE (
    ID_SERIE          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ITEM_TREINO    NUMBER NOT NULL,
    COD_SERIE         VARCHAR2(50) NOT NULL,
    NUMERO_SERIE      NUMBER NOT NULL,
    REPETICOES        NUMBER NOT NULL,
    CARGA             NUMBER(6,2) NOT NULL,

    CONSTRAINT PK_TRE_SERIE PRIMARY KEY (ID_SERIE),
    CONSTRAINT UK_TRE_SERIE_COD UNIQUE (COD_SERIE),
    CONSTRAINT FK_SERIE_ITEM FOREIGN KEY (ID_ITEM_TREINO) REFERENCES TRE_ITEM_TREINO(ID_ITEM_TREINO)
);
