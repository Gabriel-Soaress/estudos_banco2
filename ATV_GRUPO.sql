    P_DESC    TRE_EXERCICIO.DESCRICAO%TYPE

)IS
    V_ID_USER TRE_USUARIO.id_usuario%type:=NULL;
    V_ID_GRP TRE_GRUPOMUSCULAR.ID_GRP_MUSCULAR%TYPE;
